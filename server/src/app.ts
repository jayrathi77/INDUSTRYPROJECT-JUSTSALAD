import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import cookieParser from 'cookie-parser';
import rateLimit from 'express-rate-limit';
import { config } from './config/env.js';
import { authRouter } from './routes/auth.js';
import { menuRouter } from './routes/menu.js';
import { orderRouter } from './routes/orders.js';
import { adminRouter } from './routes/admin.js';
import { enquiryRouter } from './routes/enquiries.js';
import { subscriptionRouter } from './routes/subscriptions.js';
import { errorHandler, notFound } from './middleware/errors.js';
export const app = express();
app.disable('x-powered-by');
app.use(helmet());
app.use(cors({ origin: config.clientOrigin, credentials: true }));
app.use(express.json({ limit: '32kb' }));
app.use(cookieParser());
app.use('/api', rateLimit({ windowMs: 15 * 60 * 1000, limit: 300, standardHeaders: 'draft-7', legacyHeaders: false }));
app.use('/api/auth', rateLimit({ windowMs: 15 * 60 * 1000, limit: 30, standardHeaders: 'draft-7', legacyHeaders: false }), authRouter);
app.get('/api/health', (_req, res) => res.json({ ok: true, service: 'just-salad-api' }));
app.get('/api/config', (_req, res) => res.json({ swiggyListingUrl: /^https:\/\//.test(config.swiggyListingUrl) ? config.swiggyListingUrl : null, checkoutEnabled: false }));
app.use('/api/menu', menuRouter);
app.use('/api/orders', orderRouter);
app.use('/api/subscriptions', subscriptionRouter);
app.use('/api/enquiries', rateLimit({ windowMs: 60 * 60 * 1000, limit: 8, standardHeaders: 'draft-7', legacyHeaders: false }), enquiryRouter);
app.use('/api/admin', adminRouter);
app.use(notFound);
app.use(errorHandler);
